/**
 * Branded HTML and Text Email Templates for End of Day Reports
 */

function escapeHtml(value) {
  return String(value ?? '')
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#39;');
}

function renderListHtml(items, emptyLabel = 'None reported') {
  if (!items || !items.length) {
    return `<p style="margin:4px 0;font-size:13px;color:#6b7280;font-style:italic">${escapeHtml(emptyLabel)}</p>`;
  }
  const clean = items.filter(Boolean);
  if (!clean.length) {
    return `<p style="margin:4px 0;font-size:13px;color:#6b7280;font-style:italic">${escapeHtml(emptyLabel)}</p>`;
  }
  return `<ul style="margin:6px 0 10px 18px;padding:0;font-size:13px;line-height:1.5;color:#1f2937">
    ${clean.map((item) => `<li style="margin-bottom:4px">${escapeHtml(item)}</li>`).join('')}
  </ul>`;
}

function emailWrapper(title, contentHtml) {
  return `<!doctype html>
<html lang="en">
<head>
  <meta charset="utf-8">
  <meta name="viewport" content="width=device-width,initial-scale=1">
  <title>${escapeHtml(title)}</title>
</head>
<body style="margin:0;padding:0;background:#f4f5f7;font-family:-apple-system,BlinkMacSystemFont,'Segoe UI',Roboto,Helvetica,Arial,sans-serif;color:#172b4d">
  <table role="presentation" width="100%" cellpadding="0" cellspacing="0" style="background:#f4f5f7">
    <tr>
      <td align="center" style="padding:28px 12px">
        <table role="presentation" width="640" cellpadding="0" cellspacing="0" style="width:640px;max-width:100%;background:#ffffff;border:1px solid #dfe1e6;border-radius:8px;overflow:hidden">
          <tr>
            <td style="padding:18px 24px;border-bottom:1px solid #dfe1e6;background:#ffffff">
              <span style="display:inline-block;width:24px;height:24px;line-height:24px;text-align:center;border-radius:4px;background:#0c66e4;color:#ffffff;font-weight:700;font-size:13px">T</span>
              <span style="margin-left:8px;font-size:16px;font-weight:600;vertical-align:middle;color:#1b2a4a">Ticket Manager</span>
              <span style="float:right;font-size:12px;color:#626f86;line-height:24px">End of Day Report</span>
            </td>
          </tr>
          <tr>
            <td style="padding:24px">
              ${contentHtml}
            </td>
          </tr>
          <tr>
            <td style="padding:16px 24px;border-top:1px solid #dfe1e6;font-size:12px;color:#8590a2;background:#f7f8fa">
              This is an automated report generated by Serphawk Ticket Manager based on verified daily submissions and board activity.
            </td>
          </tr>
        </table>
      </td>
    </tr>
  </table>
</body>
</html>`;
}

/**
 * Builds email for an individual Developer/Employee
 * Contains ONLY their own detailed work summary and the overall team summary.
 */
export function buildEmployeeEodEmail({ reportDate, employeeName, employeeSummary, teamSummary }) {
  const subject = `[Ticket Manager] End of Day Summary - ${reportDate} - ${employeeName}`;

  const textLines = [
    `Hello ${employeeName},`,
    '',
    `Here is your End of Day Summary and Team Overview for ${reportDate}.`,
    '',
    '=== OVERALL TEAM SUMMARY ===',
    teamSummary.headline || 'Team Overview',
    teamSummary.summaryText || '',
    '',
    `=== YOUR WORK SUMMARY (${employeeName}) ===`,
    `Task Sheet Status: ${employeeSummary.taskSheetSubmitted ? `Submitted (${employeeSummary.hoursWorked}h logged)` : 'Task Sheet Not Submitted'}`,
    `Projects: ${employeeSummary.projectsWorkedOn?.join(', ') || 'Not reported'}`,
    '',
    'Completed Work:',
    ...(employeeSummary.completedWork?.map((w) => ` - ${w}`) || [' - None reported']),
    '',
    'In-Progress Work:',
    ...(employeeSummary.inProgressWork?.map((w) => ` - ${w}`) || [' - None reported']),
    '',
    'Blockers & Challenges:',
    ...(employeeSummary.blockers?.map((b) => ` - ${b}`) || [' - No blockers reported']),
    '',
    'Next Steps:',
    ...(employeeSummary.nextSteps?.map((s) => ` - ${s}`) || [' - Proceed with board priorities']),
    '',
    `Progress Assessment: ${employeeSummary.overallProgress || 'Routine work progression.'}`,
    '',
    'Regards,',
    'Serphawk Ticket Manager',
  ];

  const contentHtml = `
    <h1 style="margin:0 0 4px;font-size:20px;line-height:1.3;color:#1b2a4a">End of Day Summary</h1>
    <p style="margin:0 0 20px;font-size:13px;color:#626f86">${escapeHtml(reportDate)} · Prepared for ${escapeHtml(employeeName)}</p>

    <p style="margin:0 0 16px;font-size:14px;color:#172b4d">Hello <strong>${escapeHtml(employeeName)}</strong>,</p>
    <p style="margin:0 0 20px;font-size:14px;color:#44546f;line-height:1.5">Here is your individual daily work summary along with the overall team progress for <strong>${escapeHtml(reportDate)}</strong>.</p>

    <!-- Team Overview Card -->
    <div style="margin:0 0 20px;padding:16px;border:1px solid #dfe1e6;border-radius:6px;background:#f7f8fa">
      <h2 style="margin:0 0 6px;font-size:15px;font-weight:700;color:#0c66e4">${escapeHtml(teamSummary.headline || 'Team Velocity & Progress')}</h2>
      <p style="margin:0;font-size:13px;line-height:1.5;color:#334155">${escapeHtml(teamSummary.summaryText)}</p>
    </div>

    <!-- Personal Summary Card -->
    <div style="margin:0 0 20px;padding:18px;border:1px solid #e2e8f0;border-radius:6px;background:#ffffff">
      <div style="display:flex;align-items:center;justify-content:space-between;margin-bottom:12px;border-bottom:1px solid #f1f5f9;padding-bottom:10px">
        <h2 style="margin:0;font-size:16px;font-weight:700;color:#0f172a">Your Daily Summary</h2>
        <span style="font-size:12px;font-weight:600;padding:2px 8px;border-radius:12px;background:${employeeSummary.taskSheetSubmitted ? '#dcfce7;color:#15803d' : '#fee2e2;color:#b91c1c'}">
          ${employeeSummary.taskSheetSubmitted ? `Task Sheet Filed (${employeeSummary.hoursWorked}h)` : 'Task Sheet Not Submitted'}
        </span>
      </div>

      <p style="margin:4px 0 8px;font-size:13px;color:#475467"><strong>Projects:</strong> ${escapeHtml(employeeSummary.projectsWorkedOn?.join(', ') || 'Not reported')}</p>

      <div style="margin-top:12px">
        <span style="font-size:12px;font-weight:700;color:#1e293b;text-transform:uppercase;letter-spacing:.04em">Completed Work</span>
        ${renderListHtml(employeeSummary.completedWork)}
      </div>

      <div style="margin-top:12px">
        <span style="font-size:12px;font-weight:700;color:#1e293b;text-transform:uppercase;letter-spacing:.04em">In-Progress Work</span>
        ${renderListHtml(employeeSummary.inProgressWork)}
      </div>

      <div style="margin-top:12px">
        <span style="font-size:12px;font-weight:700;color:#b91c1c;text-transform:uppercase;letter-spacing:.04em">Blockers &amp; Challenges</span>
        ${renderListHtml(employeeSummary.blockers, 'No blockers reported')}
      </div>

      <div style="margin-top:12px">
        <span style="font-size:12px;font-weight:700;color:#0369a1;text-transform:uppercase;letter-spacing:.04em">Next Steps</span>
        ${renderListHtml(employeeSummary.nextSteps)}
      </div>

      <div style="margin-top:14px;padding:10px 12px;border-radius:4px;background:#f8fafc;border-left:3px solid #0c66e4">
        <span style="font-size:12px;font-weight:700;color:#0c66e4">Progress Assessment: </span>
        <span style="font-size:13px;color:#334155">${escapeHtml(employeeSummary.overallProgress)}</span>
      </div>
    </div>
  `;

  return {
    subject,
    text: textLines.join('\n'),
    html: emailWrapper(subject, contentHtml),
  };
}

/**
 * Builds email for Admins
 * Contains the COMPLETE report: team summary, metrics, management recommendations,
 * project-wise progress, high-priority issues, overdue tickets, and all employees' detailed summaries.
 */
export function buildAdminEodEmail({
  reportDate,
  adminName,
  metrics,
  teamSummary,
  managementSummary,
  projectSummaries,
  employeeSummaries,
  highPriorityTickets,
  overdueTickets,
}) {
  const subject = `[Ticket Manager] Consolidated End of Day Report - ${reportDate}`;

  const textLines = [
    `Hello ${adminName},`,
    '',
    `Please find the consolidated End of Day Report for ${reportDate}.`,
    '',
    '=== TEAM OVERVIEW & METRICS ===',
    teamSummary.headline || 'Team Overview',
    teamSummary.summaryText || '',
    `Submissions: ${metrics.submittedCount} of ${metrics.totalEmployees} employees (${metrics.missingCount} missing)`,
    `Total Logged Hours: ${metrics.totalHoursLogged}h`,
    `Completed Today: ${metrics.totalCompletedToday} tickets`,
    `Active High Priority: ${metrics.totalHighPriority} tickets`,
    `Overdue: ${metrics.totalOverdue} tickets`,
    '',
    '=== MANAGEMENT RECOMMENDATIONS ===',
    ...(managementSummary.recommendations?.map((r) => ` • ${r}`) || [' • None recorded']),
    '',
    '=== HIGH PRIORITY & OVERDUE TICKETS ===',
    `High Priority: ${highPriorityTickets.length ? highPriorityTickets.map((t) => `${t.key}: ${t.title} (${t.assignee})`).join('; ') : 'None'}`,
    `Overdue: ${overdueTickets.length ? overdueTickets.map((t) => `${t.key} (due ${t.dueDate}): ${t.title} (${t.assignee})`).join('; ') : 'None'}`,
    '',
    '=== EMPLOYEE SUMMARIES ===',
    ...employeeSummaries.map((emp) => [
      `--- ${emp.employeeName} (${emp.taskSheetSubmitted ? `Filed ${emp.hoursWorked}h` : 'Task Sheet Not Submitted'}) ---`,
      `Projects: ${emp.projectsWorkedOn?.join(', ') || 'None'}`,
      `Completed: ${emp.completedWork?.join('; ') || 'None'}`,
      `In Progress: ${emp.inProgressWork?.join('; ') || 'None'}`,
      `Blockers: ${emp.blockers?.join('; ') || 'None'}`,
      `Progress: ${emp.overallProgress || 'N/A'}`,
      '',
    ]).flat(),
    'Regards,',
    'Serphawk Ticket Manager',
  ];

  const employeeCardsHtml = employeeSummaries
    .map(
      (emp) => `
    <div style="margin:0 0 16px;padding:14px;border:1px solid #e2e8f0;border-radius:6px;background:#ffffff">
      <div style="display:flex;align-items:center;justify-content:space-between;margin-bottom:8px">
        <strong style="font-size:14px;color:#0f172a">${escapeHtml(emp.employeeName)}</strong>
        <span style="font-size:11px;font-weight:600;padding:2px 6px;border-radius:10px;background:${emp.taskSheetSubmitted ? '#dcfce7;color:#15803d' : '#fee2e2;color:#b91c1c'}">
          ${emp.taskSheetSubmitted ? `${emp.hoursWorked}h logged` : 'Task Sheet Not Submitted'}
        </span>
      </div>
      <p style="margin:2px 0 6px;font-size:12px;color:#64748b"><strong>Projects:</strong> ${escapeHtml(emp.projectsWorkedOn?.join(', ') || 'Not reported')}</p>
      <div style="font-size:12px;color:#334155;margin-bottom:4px"><strong>Completed:</strong> ${escapeHtml(emp.completedWork?.join(', ') || 'None reported')}</div>
      <div style="font-size:12px;color:#334155;margin-bottom:4px"><strong>In Progress:</strong> ${escapeHtml(emp.inProgressWork?.join(', ') || 'None reported')}</div>
      ${emp.blockers?.length && !emp.blockers[0].startsWith('No blockers') && !emp.blockers[0].startsWith('Task Sheet') ? `<div style="font-size:12px;color:#b91c1c;margin-bottom:4px"><strong>Blocker:</strong> ${escapeHtml(emp.blockers.join('; '))}</div>` : ''}
      <div style="font-size:12px;color:#0284c7;margin-top:6px"><em>${escapeHtml(emp.overallProgress)}</em></div>
    </div>`
    )
    .join('');

  const projectCardsHtml = projectSummaries
    .map(
      (p) => `
    <div style="margin:0 0 10px;padding:12px;border:1px solid #e2e8f0;border-radius:6px;background:#ffffff">
      <div style="display:flex;align-items:center;justify-content:space-between">
        <strong style="font-size:13px;color:#0f172a">${escapeHtml(p.projectName)} (${escapeHtml(p.projectKey)})</strong>
        <span style="font-size:11px;font-weight:600;color:${p.overdue > 0 ? '#b91c1c' : '#15803d'}">${escapeHtml(p.status)}</span>
      </div>
      <p style="margin:4px 0 0;font-size:12px;color:#475467">${escapeHtml(p.summary)}</p>
    </div>`
    )
    .join('');

  const contentHtml = `
    <h1 style="margin:0 0 4px;font-size:20px;line-height:1.3;color:#1b2a4a">Consolidated End of Day Report</h1>
    <p style="margin:0 0 20px;font-size:13px;color:#626f86">${escapeHtml(reportDate)} · Executive Briefing for ${escapeHtml(adminName)}</p>

    <!-- Metrics Bar -->
    <table role="presentation" width="100%" cellpadding="0" cellspacing="0" style="margin-bottom:20px;background:#f8fafc;border:1px solid #e2e8f0;border-radius:6px">
      <tr>
        <td style="padding:12px;text-align:center;border-right:1px solid #e2e8f0">
          <div style="font-size:18px;font-weight:700;color:#0f172a">${metrics.submittedCount}/${metrics.totalEmployees}</div>
          <div style="font-size:11px;color:#64748b;text-transform:uppercase">Submissions</div>
        </td>
        <td style="padding:12px;text-align:center;border-right:1px solid #e2e8f0">
          <div style="font-size:18px;font-weight:700;color:#0c66e4">${metrics.totalHoursLogged}h</div>
          <div style="font-size:11px;color:#64748b;text-transform:uppercase">Hours Logged</div>
        </td>
        <td style="padding:12px;text-align:center;border-right:1px solid #e2e8f0">
          <div style="font-size:18px;font-weight:700;color:#16a34a">${metrics.totalCompletedToday}</div>
          <div style="font-size:11px;color:#64748b;text-transform:uppercase">Completed Today</div>
        </td>
        <td style="padding:12px;text-align:center;border-right:1px solid #e2e8f0">
          <div style="font-size:18px;font-weight:700;color:#ea580c">${metrics.totalHighPriority}</div>
          <div style="font-size:11px;color:#64748b;text-transform:uppercase">High Priority</div>
        </td>
        <td style="padding:12px;text-align:center">
          <div style="font-size:18px;font-weight:700;color:#dc2626">${metrics.totalOverdue}</div>
          <div style="font-size:11px;color:#64748b;text-transform:uppercase">Overdue</div>
        </td>
      </tr>
    </table>

    <!-- Executive Team Summary -->
    <div style="margin:0 0 20px;padding:16px;border:1px solid #dfe1e6;border-radius:6px;background:#f7f8fa">
      <h2 style="margin:0 0 6px;font-size:15px;font-weight:700;color:#0c66e4">${escapeHtml(teamSummary.headline || 'Executive Team Summary')}</h2>
      <p style="margin:0;font-size:13px;line-height:1.5;color:#334155">${escapeHtml(teamSummary.summaryText)}</p>
    </div>

    <!-- Management Recommendations -->
    <div style="margin:0 0 20px;padding:16px;border:1px solid #fed7aa;border-radius:6px;background:#fffaf0">
      <h3 style="margin:0 0 8px;font-size:14px;font-weight:700;color:#9a3412">Management Recommendations &amp; Action Items</h3>
      ${renderListHtml(managementSummary.recommendations)}
    </div>

    <!-- Project Progress -->
    <h3 style="margin:20px 0 10px;font-size:14px;font-weight:700;color:#0f172a">Project-Wise Progress</h3>
    ${projectCardsHtml || '<p style="font-size:13px;color:#64748b">No project activity recorded.</p>'}

    <!-- Employee Individual Summaries -->
    <h3 style="margin:24px 0 10px;font-size:14px;font-weight:700;color:#0f172a">Individual Employee Summaries (${employeeSummaries.length})</h3>
    ${employeeCardsHtml}
  `;

  return {
    subject,
    text: textLines.join('\n'),
    html: emailWrapper(subject, contentHtml),
  };
}

