test('7. Foreign key definitions and delete behavior', async () => {
  // Verify project_id ON DELETE CASCADE
  const pRes = await client.query("INSERT INTO public.projects (key, name) VALUES ('FKTEST', 'FK Test Project') RETURNING id");
  const pId = pRes.rows[0].id;
  await client.query(`
    INSERT INTO public.project_repositories (project_id, github_owner, github_repo, repository_url)
    VALUES (${pId}, 'owner', 'repo', 'https://github.com/owner/repo')
  `);
  await client.query(`DELETE FROM public.projects WHERE id = ${pId}`);
  const rCount = (await client.query(`SELECT count(*) FROM public.project_repositories WHERE project_id = ${pId}`)).rows[0].count;
  assert.equal(Number(rCount), 0, 'Repositories must be deleted via CASCADE when project is deleted');

  // Verify tickets.repository_id ON DELETE RESTRICT
  const repo = (await client.query("SELECT id FROM public.project_repositories LIMIT 1")).rows[0];
  const tRes = await client.query(`
    INSERT INTO public.tickets (title, description, created_by, repository_id)
    VALUES ('Restrict Test Ticket', 'Desc', 1, ${repo.id}) RETURNING id
  `);
  let caughtRestrict = false;
  try {
    await client.query(`DELETE FROM public.project_repositories WHERE id = ${repo.id}`);
  } catch (err) {
    caughtRestrict = err.code === '23001' || err.code === '23503';
  }
  assert.ok(caughtRestrict, 'Deleting a repository referenced by tickets must violate RESTRICT foreign key');
  await client.query(`DELETE FROM public.tickets WHERE id = ${tRes.rows[0].id}`);
});

