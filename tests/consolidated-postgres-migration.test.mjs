test.before(async () => {
  // Check if test server is already running
  let isReady = false;
  try {
    execSync(`"${PG_BIN}\\pg_isready.exe" -h 127.0.0.1 -p ${PORT}`, { stdio: 'ignore' });
    isReady = true;
  } catch {}

  if (!isReady) {
    if (fs.existsSync(DATA_DIR)) {
      fs.rmSync(DATA_DIR, { recursive: true, force: true });
    }
    fs.mkdirSync(DATA_DIR, { recursive: true });
    execSync(`"${PG_BIN}\\initdb.exe" -D "${DATA_DIR}" -U postgres -A trust --no-locale -E UTF8`, { stdio: 'ignore' });

    pgProc = spawn(`"${PG_BIN}\\postgres.exe"`, ['-D', DATA_DIR, '-p', String(PORT)], {
      shell: true,
      stdio: ['ignore', 'ignore', 'ignore'],
    });
    serverStartedByTest = true;

    for (let i = 0; i < 30; i++) {
      try {
        execSync(`"${PG_BIN}\\pg_isready.exe" -h 127.0.0.1 -p ${PORT}`, { stdio: 'ignore' });
        isReady = true;
        break;
      } catch {
        await sleep(300);
      }
    }
    if (!isReady) {
      throw new Error(`Failed to start isolated PostgreSQL on port ${PORT}`);
    }
  }

  client = new Client({
    host: '127.0.0.1',
    port: PORT,
    user: 'postgres',
    database: 'postgres',
  });
  await client.connect();
});

test.after(async () => {
  if (client) {
    await client.end().catch(() => {});
  }
  if (serverStartedByTest && pgProc) {
    try {
      execSync(`"${PG_BIN}\\pg_ctl.exe" -D "${DATA_DIR}" -m immediate stop`, { stdio: 'ignore' });
    } catch {}
    await sleep(500);
    try {
      fs.rmSync(DATA_DIR, { recursive: true, force: true });
    } catch {}
  }
});

