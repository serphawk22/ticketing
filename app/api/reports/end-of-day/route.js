import { NextResponse } from 'next/server';
import { requireAuth } from '@/lib/auth';
import {
  getEndOfDayReport,
  generateEndOfDayReport,
  getEndOfDayReportHistory,
  sanitizeReportForUser,
} from '@/lib/endOfDayReportService';
import { isValidDateString } from '@/lib/ticketDates';

export const dynamic = 'force-dynamic';
export const runtime = 'nodejs';

export async function GET(request) {
  const session = await requireAuth();
  if (!session) {
    return NextResponse.json({ error: 'Unauthorized' }, { status: 401 });
  }

  const url = new URL(request.url);
  const dateParam = (url.searchParams.get('date') || '').trim();

  try {
    const history = await getEndOfDayReportHistory(30);

    let report = null;
    if (dateParam) {
      if (!isValidDateString(dateParam)) {
        return NextResponse.json({ error: 'Invalid date format (YYYY-MM-DD).' }, { status: 400 });
      }
      const rawReport = await getEndOfDayReport(dateParam);
      report = sanitizeReportForUser(rawReport, session.user);
    }

    return NextResponse.json({
      report,
      history,
    });
  } catch (err) {
    console.error('[end-of-day:get] Error:', err);
    return NextResponse.json({ error: 'Failed to retrieve End of Day Report.' }, { status: 500 });
  }
}

export async function POST(request) {
  const session = await requireAuth();
  if (!session) {
    return NextResponse.json({ error: 'Unauthorized' }, { status: 401 });
  }

  // Only Admin users can generate, regenerate, and send End of Day Reports
  if (session.user.role !== 'admin') {
    return NextResponse.json(
      { error: 'Forbidden: End of Day Reports can only be generated by administrators.' },
      { status: 403 }
    );
  }

  const body = await request.json().catch(() => ({}));
  const reportDate = String(body.reportDate || '').trim();
  const regenerate = Boolean(body.regenerate);
  const sendEmails = Boolean(body.sendEmails);

  if (!isValidDateString(reportDate)) {
    return NextResponse.json({ error: 'Choose a valid reporting date (YYYY-MM-DD).' }, { status: 400 });
  }

  try {
    const report = await generateEndOfDayReport({
      reportDate,
      adminUser: session.user,
      forceRegenerate: regenerate,
      sendEmails,
    });

    return NextResponse.json({
      ok: true,
      report,
    });
  } catch (err) {
    console.error('[end-of-day:post] Generation failed:', err);
    return NextResponse.json(
      { error: err?.message || 'Failed to generate End of Day Report.' },
      { status: 500 }
    );
  }
}

