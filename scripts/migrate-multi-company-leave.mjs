import { db, isRemoteDatabase } from '../lib/db.js';

export async function runMigration() {
  console.log('Running Multi-Company Leave Management Migration...');
  console.log('Database type:', isRemoteDatabase() ? 'PostgreSQL' : 'SQLite');

  const isPg = isRemoteDatabase();

  if (isPg) {
    // 1. Drop old CHECK constraints if they exist in Postgres
    await db.prepare('ALTER TABLE leave_balances DROP CONSTRAINT IF EXISTS leave_balances_leave_type_check').run().catch(e => console.log('Notice dropping leave_balances CHECK:', e.message));
    await db.prepare('ALTER TABLE leave_balance_adjustments DROP CONSTRAINT IF EXISTS leave_balance_adjustments_leave_type_check').run().catch(e => console.log('Notice dropping leave_balance_adjustments CHECK:', e.message));
    await db.prepare('ALTER TABLE employee_leave_requests DROP CONSTRAINT IF EXISTS employee_leave_requests_leave_type_check').run().catch(e => console.log('Notice dropping employee_leave_requests CHECK:', e.message));

    // 2. Create organization_leave_categories table
    await db.prepare(`
      CREATE TABLE IF NOT EXISTS organization_leave_categories (
        id                       integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        workspace_id             integer NOT NULL REFERENCES workspaces (id),
        code                     text NOT NULL,
        name                     text NOT NULL,
        description              text NOT NULL DEFAULT '',
        annual_allowance         double precision NOT NULL DEFAULT 7.0,
        eligible_employment_types text NOT NULL DEFAULT '["full_time"]',
        is_paid                  integer NOT NULL DEFAULT 1,
        allow_lop_beyond_balance integer NOT NULL DEFAULT 1,
        carry_forward_enabled    integer NOT NULL DEFAULT 0,
        max_carry_forward_days   double precision,
        expiry_rule              text NOT NULL DEFAULT 'fiscal_year_end',
        allocation_timing        text NOT NULL DEFAULT 'upfront',
        allow_half_day           integer NOT NULL DEFAULT 1,
        allow_multi_day          integer NOT NULL DEFAULT 1,
        min_advance_days         integer NOT NULL DEFAULT 0,
        allow_past_dates         integer NOT NULL DEFAULT 0,
        requires_admin_approval  integer NOT NULL DEFAULT 1,
        is_active                integer NOT NULL DEFAULT 1,
        created_at               timestamptz NOT NULL DEFAULT now(),
        updated_at               timestamptz NOT NULL DEFAULT now(),
        UNIQUE (workspace_id, code)
      )
    `).run();

    // 3. Create organization_leave_policies table
    await db.prepare(`
      CREATE TABLE IF NOT EXISTS organization_leave_policies (
        id                        integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        workspace_id              integer NOT NULL UNIQUE REFERENCES workspaces (id),
        fiscal_year_start_month   integer NOT NULL DEFAULT 4,
        new_joiner_prorata_method text NOT NULL DEFAULT 'none',
        allow_advance_leave       integer NOT NULL DEFAULT 1,
        allow_negative_balance    integer NOT NULL DEFAULT 0,
        created_at                timestamptz NOT NULL DEFAULT now(),
        updated_at                timestamptz NOT NULL DEFAULT now()
      )
    `).run();

    // 4. Add columns to employees, company_holidays, leave_balance_adjustments
    await db.prepare(`
      DO $$
      BEGIN
        IF NOT EXISTS (SELECT 1 FROM information_schema.columns WHERE table_schema='public' AND table_name='employees' AND column_name='workspace_id') THEN
          ALTER TABLE employees ADD COLUMN workspace_id integer REFERENCES workspaces (id);
        END IF;
        IF NOT EXISTS (SELECT 1 FROM information_schema.columns WHERE table_schema='public' AND table_name='company_holidays' AND column_name='workspace_id') THEN
          ALTER TABLE company_holidays ADD COLUMN workspace_id integer REFERENCES workspaces (id);
        END IF;
        IF NOT EXISTS (SELECT 1 FROM information_schema.columns WHERE table_schema='public' AND table_name='leave_balance_adjustments' AND column_name='workspace_id') THEN
          ALTER TABLE leave_balance_adjustments ADD COLUMN workspace_id integer REFERENCES workspaces (id);
        END IF;
      END $$;
    `).run();

  } else {
    // SQLite dialect
    await db.prepare(`
      CREATE TABLE IF NOT EXISTS organization_leave_categories (
        id                       INTEGER PRIMARY KEY AUTOINCREMENT,
        workspace_id             INTEGER NOT NULL REFERENCES workspaces(id),
        code                     TEXT NOT NULL,
        name                     TEXT NOT NULL,
        description              TEXT NOT NULL DEFAULT '',
        annual_allowance         REAL NOT NULL DEFAULT 7.0,
        eligible_employment_types TEXT NOT NULL DEFAULT '["full_time"]',
        is_paid                  INTEGER NOT NULL DEFAULT 1,
        allow_lop_beyond_balance INTEGER NOT NULL DEFAULT 1,
        carry_forward_enabled    INTEGER NOT NULL DEFAULT 0,
        max_carry_forward_days   REAL,
        expiry_rule              TEXT NOT NULL DEFAULT 'fiscal_year_end',
        allocation_timing        TEXT NOT NULL DEFAULT 'upfront',
        allow_half_day           INTEGER NOT NULL DEFAULT 1,
        allow_multi_day          INTEGER NOT NULL DEFAULT 1,
        min_advance_days         INTEGER NOT NULL DEFAULT 0,
        allow_past_dates         INTEGER NOT NULL DEFAULT 0,
        requires_admin_approval  INTEGER NOT NULL DEFAULT 1,
        is_active                INTEGER NOT NULL DEFAULT 1,
        created_at               TEXT NOT NULL DEFAULT (datetime('now')),
        updated_at               TEXT NOT NULL DEFAULT (datetime('now')),
        UNIQUE(workspace_id, code)
      )
    `).run();

    await db.prepare(`
      CREATE TABLE IF NOT EXISTS organization_leave_policies (
        id                        INTEGER PRIMARY KEY AUTOINCREMENT,
        workspace_id              INTEGER NOT NULL UNIQUE REFERENCES workspaces(id),
        fiscal_year_start_month   INTEGER NOT NULL DEFAULT 4,
        new_joiner_prorata_method TEXT NOT NULL DEFAULT 'none',
        allow_advance_leave       INTEGER NOT NULL DEFAULT 1,
        allow_negative_balance    INTEGER NOT NULL DEFAULT 0,
        created_at                TEXT NOT NULL DEFAULT (datetime('now')),
        updated_at                TEXT NOT NULL DEFAULT (datetime('now'))
      )
    `).run();

    // Add columns if they do not exist in SQLite
    const empCols = await db.prepare('PRAGMA table_info(employees)').all();
    if (!empCols.some(c => c.name === 'workspace_id')) {
      await db.prepare('ALTER TABLE employees ADD COLUMN workspace_id INTEGER REFERENCES workspaces(id)').run();
    }
    const holCols = await db.prepare('PRAGMA table_info(company_holidays)').all();
    if (!holCols.some(c => c.name === 'workspace_id')) {
      await db.prepare('ALTER TABLE company_holidays ADD COLUMN workspace_id INTEGER REFERENCES workspaces(id)').run();
    }
    const adjCols = await db.prepare('PRAGMA table_info(leave_balance_adjustments)').all();
    if (!adjCols.some(c => c.name === 'workspace_id')) {
      await db.prepare('ALTER TABLE leave_balance_adjustments ADD COLUMN workspace_id INTEGER REFERENCES workspaces(id)').run();
    }
  }

  // 5. Seed default categories and policies for all workspaces
  const workspaces = await db.prepare('SELECT id, name FROM workspaces').all();
  console.log(`Found ${workspaces.length} workspaces:`, workspaces.map(w => `${w.id}:${w.name}`).join(', '));

  for (const ws of workspaces) {
    // Policy
    if (isPg) {
      await db.prepare(`
        INSERT INTO organization_leave_policies (workspace_id, fiscal_year_start_month, new_joiner_prorata_method)
        VALUES (?, 4, 'none')
        ON CONFLICT (workspace_id) DO NOTHING
      `).run(ws.id);
    } else {
      await db.prepare(`
        INSERT OR IGNORE INTO organization_leave_policies (workspace_id, fiscal_year_start_month, new_joiner_prorata_method)
        VALUES (?, 4, 'none')
      `).run(ws.id);
    }

    // Default categories: Casual, Sick, Optional
    const defaultCategories = [
      {
        code: 'casual',
        name: 'Casual Leave (CL)',
        description: 'Standard annual casual leave for personal reasons.',
        allowance: 7.0,
        roles: JSON.stringify(['full_time']),
        is_paid: 1,
        allow_lop: 1,
        carry_forward: 0,
        max_cf: null,
        advance: 7,
        past_dates: 0,
        active: 1,
      },
      {
        code: 'sick',
        name: 'Sick Leave (SL)',
        description: 'Medical leave for personal illness or health emergencies.',
        allowance: 7.0,
        roles: JSON.stringify(['full_time', 'part_time', 'intern', 'probation', 'freelancer']),
        is_paid: 1,
        allow_lop: 1,
        carry_forward: 1,
        max_cf: null,
        advance: 0,
        past_dates: 1,
        active: 1,
      },
      {
        code: 'optional',
        name: 'Optional Leave',
        description: 'Floating or optional holiday leave configurable by company.',
        allowance: 0.0,
        roles: JSON.stringify(['full_time']),
        is_paid: 1,
        allow_lop: 0,
        carry_forward: 0,
        max_cf: null,
        advance: 0,
        past_dates: 0,
        active: 0,
      },
    ];

    for (const cat of defaultCategories) {
      if (isPg) {
        await db.prepare(`
          INSERT INTO organization_leave_categories (
            workspace_id, code, name, description, annual_allowance, eligible_employment_types,
            is_paid, allow_lop_beyond_balance, carry_forward_enabled, max_carry_forward_days,
            min_advance_days, allow_past_dates, is_active
          ) VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)
          ON CONFLICT (workspace_id, code) DO NOTHING
        `).run(
          ws.id, cat.code, cat.name, cat.description, cat.allowance, cat.roles,
          cat.is_paid, cat.allow_lop, cat.carry_forward, cat.max_cf,
          cat.advance, cat.past_dates, cat.active
        );
      } else {
        await db.prepare(`
          INSERT OR IGNORE INTO organization_leave_categories (
            workspace_id, code, name, description, annual_allowance, eligible_employment_types,
            is_paid, allow_lop_beyond_balance, carry_forward_enabled, max_carry_forward_days,
            min_advance_days, allow_past_dates, is_active
          ) VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)
        `).run(
          ws.id, cat.code, cat.name, cat.description, cat.allowance, cat.roles,
          cat.is_paid, cat.allow_lop, cat.carry_forward, cat.max_cf,
          cat.advance, cat.past_dates, cat.active
        );
      }
    }
  }

  // 6. Backfill existing employees without workspace_id
  if (workspaces.length > 0) {
    const primaryWsId = workspaces[0].id;
    await db.prepare(`
      UPDATE employees
      SET workspace_id = ?
      WHERE workspace_id IS NULL
    `).run(primaryWsId);
    console.log(`Backfilled employees with primary workspace ID ${primaryWsId}.`);
  }

  console.log('Multi-Company Leave Management Migration completed successfully!');
}

if (process.argv[1]?.endsWith('migrate-multi-company-leave.mjs')) {
  runMigration().then(() => process.exit(0)).catch(err => {
    console.error(err);
    process.exit(1);
  });
}
